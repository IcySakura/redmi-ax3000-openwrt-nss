#!/bin/sh
# Print a package profile that reproduces what is installed on a running router.
#
#   scripts/router-packages.sh root@ROUTER > profiles/my-router.packages
#
# Compares the image's package list (/rom/etc/apk/world) with the current one
# (/etc/apk/world): the output is the profile the image was built from, plus
# every package installed since and "-name" for every package removed since.
# Review the result before committing it - it lists everything you run.
set -eu

host=${1:?usage: $0 root@ROUTER}

ssh "$host" '
	cat /etc/ra81-nss/profile.packages 2>/dev/null
	echo "@@ROM"; cat /rom/etc/apk/world
	echo "@@NOW"; cat /etc/apk/world
	echo "@@INFO"; cat /etc/ra81-nss/build-info 2>/dev/null
' | awk '
	/^@@ROM$/ { s = "rom"; next }
	/^@@NOW$/ { s = "now"; next }
	/^@@INFO$/ { s = "info"; next }
	s == "" { base[++nb] = $0; next }
	s == "info" { if (sub(/^PROFILE=/, "")) profile = $0; next }
	{
		# drop version constraints (name=ver, name~ver, name>=ver ...)
		n = $0; sub(/[=<>~].*/, "", n)
		if (n == "") next
		if (s == "rom") rom[n] = 1; else now[n] = 1
	}
	END {
		printf "# Generated by scripts/router-packages.sh from a router built with profile \"%s\".\n", profile
		for (i = 1; i <= nb; i++) print base[i]
		print ""
		print "# Changes on the router since that image:"
		for (n in now) if (!(n in rom)) add[n] = 1
		for (n in rom) if (!(n in now)) del[n] = 1
		for (n in add) print n | "sort"; close("sort")
		for (n in del) print "-" n | "sort"; close("sort")
	}
'
